const byId = new Map(GENERALS.map((g) => [g.id, g]))

export function getGeneral(id: string): GeneralDef {
  const g = byId.get(id)
  if (!g) throw new Error(`Unknown general ${id}`)
  return g
}

export function listGeneralsForPick(packs?: PackId[]): GeneralDef[] {
  const exclude = new Set([
    'soldier',
    'huaxiong',
    'zhangxiu',
    'yuanshao',
    'yanbaihu',
    'liubiao',
  ])
  const packSet = packs?.length ? new Set(packs) : null
  return GENERALS.filter((g) => {
    if (exclude.has(g.id)) return false
    if (packSet && !packSet.has(g.pack)) return false
    return true
  })
}
